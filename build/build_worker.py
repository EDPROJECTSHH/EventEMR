#!/usr/bin/env python3
"""
functions/api/*.js  ->  dist/_worker.js

Cloudflare Pages is deployed here by Direct Upload rather than the Git
integration, which means Pages never compiles the functions/ directory for us.
Advanced Mode is the supported way in: a single _worker.js at the root of the
uploaded assets handles every request. This script builds it.

Two consequences are handled here rather than silently lost:
  * Advanced Mode stops Pages processing _headers and _redirects, so the worker
    applies the security headers, the cache rules and the single-page fallback
    itself.
  * sync.js and drive.js each declare helpers of the same name (route,
    headersFor, niceError, ENV ...), so each is wrapped in its own closure.
    Sharing a scope would have one quietly overwrite the other.

Run by build_dist.py, so editing functions/api/*.js is enough — there is no
separate step to forget.
"""

import io
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FUNCS = os.path.join(ROOT, 'functions', 'api')
DIST = os.path.join(ROOT, 'dist')


def module_iife(path, name):
    with io.open(path, encoding='utf-8') as f:
        s = f.read()
    s = re.sub(r'^export \{[^}]*\};\s*$', '', s, flags=re.M)
    s = re.sub(r'^export (async function|function|const|let)', r'\1', s, flags=re.M)
    return ('/* ===================== %s ===================== */\n'
            'const %s = (function () {\n%s\n  return { onRequest: onRequest };\n})();\n\n'
            % (os.path.relpath(path, ROOT), name, s))


HEAD = '''/* GENERATED by build/build_worker.py from functions/api/*.js — do not edit.
 * Cloudflare Pages Advanced Mode worker; see that script for why this exists.
 */

'''

TAIL = r'''/* ----------------------------------------------------------- static assets -- */

const SECURITY = {
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'geolocation=(), microphone=(), camera=()',
  'Content-Security-Policy':
    "default-src 'self'; script-src 'self' 'unsafe-inline'; " +
    "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; " +
    "font-src 'self' https://fonts.gstatic.com; img-src 'self' data: blob:; " +
    "connect-src 'self'; form-action 'self'; base-uri 'self'; object-src 'none'; " +
    "frame-ancestors 'self'"
};

function cacheFor(pathname) {
  /* The service worker must never be served stale, or a redeploy never reaches
     the field and a tablet runs last week's build all event. */
  if (pathname === '/sw.js') return 'no-cache, no-store, must-revalidate';
  if (pathname === '/' || pathname === '/index.html') return 'no-cache';
  if (pathname === '/app.js') return 'public, max-age=0, must-revalidate';
  if (pathname.indexOf('/data/') === 0) return 'public, max-age=0, must-revalidate';
  if (pathname.indexOf('/assets/') === 0) return 'public, max-age=604800';
  return '';
}

function decorate(res, pathname) {
  const out = new Response(res.body, res);
  for (const k in SECURITY) out.headers.set(k, SECURITY[k]);
  const cc = cacheFor(pathname);
  if (cc) out.headers.set('Cache-Control', cc);
  return out;
}

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    const ctxLike = { request: request, env: env, ctx: ctx };

    if (url.pathname === '/api/sync') return SYNC.onRequest(ctxLike);
    if (url.pathname === '/api/drive') return DRIVE.onRequest(ctxLike);

    const res = await env.ASSETS.fetch(request);

    /* Single-page fallback. Only for navigations: answering a missing .js or
       .json with the HTML shell turns a 404 into a baffling parse error. */
    if (res.status === 404 && request.method === 'GET' &&
        (request.headers.get('accept') || '').indexOf('text/html') !== -1) {
      const shell = await env.ASSETS.fetch(new URL('/index.html', url).toString());
      return decorate(shell, '/index.html');
    }
    return decorate(res, url.pathname);
  }
};
'''


def build():
    out = HEAD
    out += module_iife(os.path.join(FUNCS, 'sync.js'), 'SYNC')
    out += module_iife(os.path.join(FUNCS, 'drive.js'), 'DRIVE')
    out += TAIL
    os.makedirs(DIST, exist_ok=True)
    path = os.path.join(DIST, '_worker.js')
    with io.open(path, 'w', encoding='utf-8') as f:
        f.write(out)
    return path, len(out)


if __name__ == '__main__':
    p, n = build()
    print('  dist/_worker.js    %d KB' % (n // 1024))
